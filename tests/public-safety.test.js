const assert = require('assert/strict');
const {
  inspectText,
  prohibitedPath,
  assertPublicText,
} = require('../scripts/public-safety');

for (const file of [
  'backup/homey/snapshot.json',
  'reports/report.md',
  'review/a.patch',
  'diagnostics/run/report.ru.md',
  'maintenance-confirmed.json',
  '.env.local',
  'review.patch',
])
  assert.equal(prohibitedPath(file), true, file);
for (const file of [
  'tests/fixtures/snapshot-synthetic.json',
  'diagnostics/fixtures/synthetic.json',
  'diagnostics/tests/reproduce.js',
  'docs/Privacy.md',
  '.env.example',
  'simulator/scenarios/stability-diagnostics-write-failure.json',
])
  assert.equal(prohibitedPath(file), false, file);
assert.deepEqual(inspectText('HOMEY_API_TOKEN=YOUR_HOMEY_API_TOKEN', ''), []);
assert.deepEqual(inspectText('sha256: ' + 'a'.repeat(64), ''), []);
assert.deepEqual(inspectText('ghp_' + 'x'.repeat(36), ''), ['github-token']);
assert.deepEqual(inspectText('-----BEGIN ' + 'PRIVATE KEY-----', ''), [
  'private-key',
]);
assert.deepEqual(inspectText('apiToken="' + 'x'.repeat(32) + '"', ''), [
  'credential-literal',
]);
const token = 'synthetic-test-token-value';
assert.deepEqual(inspectText('embedded ' + token, token), [
  'environment-token',
]);
assert.throws(
  () => assertPublicText('bundle.js', 'ghp_' + 'x'.repeat(36)),
  /bundle.js: github-token/,
);
console.log(
  'PASS public safety: forbidden paths, retained fixtures, placeholders, embedded secrets',
);

// Both shells must accept the timestamped backup IDs generated by discovery.
const workflow = require('fs').readFileSync(
  require('path').join(
    __dirname,
    '../deployment/private-repository/smartcharge-deploy.yml',
  ),
  'utf8',
);
const backupPatternText = '^[a-zA-Z0-9][a-zA-Z0-9.-]*$';
assert.equal(workflow.split(backupPatternText).length - 1, 2);
{
  const pattern = new RegExp(backupPatternText);
  assert.equal(
    pattern.test(
      '2026-10-11T13-00-18.897Z-6987b8c1-efd2-4760-9f08-43218bddab58',
    ),
    true,
  );
  for (const invalid of ['..', '../backup', 'a/b', 'a\\b'])
    assert.equal(pattern.test(invalid), false);
}
